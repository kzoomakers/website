import { cleanHtml } from "@/lib/sanitize";
import type { Comment } from "../models/story-page";
import { zoned } from "../util";
import { TimeLabel, newAria, titlePath } from "./story-list";

const COLLAPSE_SCORE = -5, SCORE_RANGE_TO_HIDE = [-2, 4];
export const html = (h: string | null) => ({ __html: cleanHtml(h ?? "") }); // stored HTML is generated by us, but it is cleaned again on the way out

/** application_helper upvoter_score (number_to_human with "%n%u"): small numbers as they are. */
const upvoterScore = (s: number | "~") => (s === "~" || Math.abs(s) < 1000 ? String(s) : `${Math.round((s / 1000) * 10) / 10}Thousand`);
const commentScore = (c: Comment): number | "~" => (c.created_at.getTime() < Date.now() - 36 * 3600_000 || c.score < SCORE_RANGE_TO_HIDE[0] || c.score > SCORE_RANGE_TO_HIDE[1] ? c.score : "~");
const goneText = (c: Comment) => c.is_moderated ? `Comment removed by moderator ${c.moderator ?? ""}: ${c.mod_reason ?? "No reason given"}` : c.user_banned_at ? "Comment from banned user removed" : "Comment removed by its author";

function Hat({ c }: { c: Comment }) {
  if (!c.hat) return null;
  const linked = !!c.hat_link && /^https?:\/\//.test(c.hat_link);
  const granted = zoned(c.hat_created_at!).date;
  return <span className={`hat hat_${c.hat.replace(/[^A-Za-z0-9]/g, "_").toLowerCase()}`} title={`Granted ${granted}${c.hat_link && !linked ? ` - ${c.hat_link}` : ""}`}>
    <span className="crown">{linked ? <a href={c.hat_link!} target="_blank" rel="noopener">{c.hat}</a> : c.hat}</span></span>;
}

/** comments/_comment.html.erb for a logged-out visitor. `showStory` adds "on: story title" (comment lists). */
export function CommentItem({ c, story, newUserDays, showStory = false }: { c: Comment; story: { id: number; user_id: number; user_is_author: boolean }; newUserDays: number; showStory?: boolean }) {
  const gone = c.is_deleted || c.is_moderated, score = commentScore(c);
  const wasMerged = story.id !== c.story_id, edited = c.last_edited_at.getTime() - c.created_at.getTime() > 60_000;
  const isNew = c.user_created_at && c.user_created_at.getTime() > Date.now() - newUserDays * 864e5;
  const ucls = [c.user_id === story.user_id && story.user_is_author && "user_is_author", c.user_id === story.user_id && "user_is_submitter", (c.user_deleted_at || c.user_banned_at) && "inactive_user", isNew && "new_user"].filter(Boolean).join(" ");
  return (
    <>
      <input id={`comment_folder_${c.short_id}`} className="comment_folder_button" type="checkbox" defaultChecked={c.score <= COLLAPSE_SCORE} />
      <div id={`c_${c.short_id}`} data-shortid={c.short_id} className={["comment", c.score < SCORE_RANGE_TO_HIDE[0] && "bad"].filter(Boolean).join(" ")}>
        <div className="voters">
          <label htmlFor={`comment_folder_${c.short_id}`} className="comment_folder" />
          {!gone && <a className="upvoter" href="/login" title={String(score)}>{upvoterScore(score)}</a>}
        </div>
        <div className="details">
          <div className="byline">
            {wasMerged && <span className="merge" aria-label="Merged" />}
            <span className="">
              <a className={ucls || undefined} aria-label={newAria(c, newUserDays, c.user_id === story.user_id ? (story.user_is_author ? "Author" : "Submitter") : undefined)} href={`/~${c.username}`}>{c.username}</a> <Hat c={c} />
              {edited ? "edited" : c.is_from_email ? "e-mailed" : ""}{" "}
              <a href={`/c/${c.short_id}`}><TimeLabel time={c.last_edited_at} /></a>
            </span>
            <span className="flagger flagger_stub" />
            {showStory && c.story_title && <> | on: <a href={titlePath({ short_id: c.story_short_id!, title: c.story_title })}>{c.story_title}</a></>}
            <span className="reason" />
          </div>
          <div role="heading" aria-level={3} className="comment_text" {...(gone ? {} : { dangerouslySetInnerHTML: html(c.markeddown_comment) })}>
            {gone ? <p><span className="na">[{goneText(c)}]</span></p> : null}
          </div>
        </div>
      </div>
    </>
  );
}

